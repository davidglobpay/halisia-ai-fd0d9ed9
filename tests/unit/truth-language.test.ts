/**
 * Truth-language source regression.
 *
 * HALISIA's public surfaces may never imply verification, partnership or legal
 * authority that the underlying evidence does not support. These checks read the
 * source files directly so a copy regression fails in CI rather than in front of
 * a buyer.
 *
 * The county group below was added after the county surface was stripped back.
 * For a long time the app shipped a livability index, a year-on-year growth
 * rate, a water-reliability score, eleven "dashboard scores", an overall
 * HALISIA score out of 100 and a per-county public-opinion index — none of
 * which had a source. Every one of them was generated by hashing the county
 * code, and they were displayed with confidence badges and citations to KNBS,
 * WASREB, Afrobarometer and TIFA. These tests exist so that cannot come back
 * quietly.
 *
 * The Send a Scout surfaces were added to this harness after shipping with the
 * meta description "Book a vetted field scout". Nothing in scout_profiles holds
 * an identity document, a credential or a reference: "vetting" is one
 * administrator typing a free-text note and setting status to approved. The
 * claim was exactly the class this file exists to catch, and it shipped only
 * because the surface was not on the list. Any new public surface belongs here
 * on the day it is written.
 *
 * The pricing surfaces were added with the price tables themselves. A price is
 * a promise, and the temptation on a pricing page is to justify the number by
 * implying the product does more than it does — that paying buys certainty,
 * protection or a guarantee. It buys a report that names its sources. The
 * pricing group below holds that line.
 *
 * The construction-cost and concept-drawing surfaces were added last, after a
 * Lovable agent run put a budget panel and a downloadable KES estimate PDF on
 * /design-studio — a public route, reachable with no account. The copy it
 * wrote was careful, but nothing held it there: a later edit could have
 * dropped "not a quote" and turned a planning range into a price. The group at
 * the end of this file pins the exact disclaimer strings.
 *
 * Those strings are matched against raw source, so their characters matter
 * more than they look. DRAWING_LABEL separates its three clauses with EN
 * DASHES (U+2013), while the conceptual-only sentence beside it uses an EM
 * DASH (U+2014). The cost panel on screen writes "low–moderate" with an en
 * dash and "not a quote" in lower case; the PDF writes "low-moderate" with an
 * ASCII hyphen and "Not a quote" capitalised, because jsPDF's Latin-1 encoding
 * forced a different character set on that file. One shared needle would pass
 * on one surface and silently leave the other unguarded, so they are asserted
 * separately and deliberately.
 */
