/**
 * Truth-language source regression.
 *
 * HALISIA's public surfaces may never imply verification, partnership or legal
 * authority that the underlying evidence does not support. These checks read the
 * source files directly so a copy regression fails in CI rather than in front of
 * a buyer.
 *
 * The county group below was added after the county surface was stripped back.
 * For a long time the app shipped a livability index, a year-on-year growth
 * rate, a water-reliability score, eleven "dashboard scores", an overall
 * HALISIA score out of 100 and a per-county public-opinion index — none of
 * which had a source. Every one of them was generated by hashing the county
 * code, and they were displayed with confidence badges and citations to KNBS,
 * WASREB, Afrobarometer and TIFA. These tests exist so that cannot come back
 * quietly.
 *
 * The Send a Scout surfaces were added to this harness after shipping with the
 * meta description "Book a vetted field scout". Nothing in scout_profiles holds
 * an identity document, a credential or a reference: "vetting" is one
 * administrator typing a free-text note and setting status to approved. The
 * claim was exactly the class this file exists to catch, and it shipped only
 * because the surface was not on the list. Any new public surface belongs here
 * on the day it is written.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

const read = (p: string) => readFileSync(resolve(process.cwd(), p), "utf8");

const LANDING = read("src/routes/index.tsx");
const SECTIONS = read("src/components/halisia/landing-sections.tsx");
const NAV_GUIDE = read("src/components/halisia/nav-guide.tsx");
const EVIDENCE = read("src/lib/evidence.ts");
const COUNTY_MAP = read("src/components/halisia/kenya-county-map.tsx");
const PDF_COMPARE = read("src/lib/pdf-county-compare.ts");
const SCOUT = read("src/routes/_authenticated/scout.tsx");
const SCOUT_HUB = read("src/components/halisia/scout-hub.tsx");

const PUBLIC_SURFACES: Array<[string, string]> = [
  ["src/routes/index.tsx", LANDING],
  ["src/components/halisia/landing-sections.tsx", SECTIONS],
  ["src/components/halisia/nav-guide.tsx", NAV_GUIDE],
  ["src/lib/evidence.ts", EVIDENCE],
  ["src/components/halisia/kenya-county-map.tsx", COUNTY_MAP],
  ["src/lib/pdf-county-compare.ts", PDF_COMPARE],
  ["src/routes/_authenticated/scout.tsx", SCOUT],
  ["src/components/halisia/scout-hub.tsx", SCOUT_HUB],
];

describe("required public wording", () => {
  it.each([
    ["Community-contributed", LANDING],
    ["Read the location profile", LANDING],
    ["every score names its sources", LANDING],
    ["confidence stated on every output", LANDING],
    ["we do not assert title, boundary or ownership", LANDING],
    ["Every listing shows its source", SECTIONS],
    ["evidence behind them", SECTIONS],
    ["Reviewed contributions add to county data completeness", SECTIONS],
    ["credentials they've submitted", SECTIONS],
    ["county emblems", NAV_GUIDE],
    // The county map and the comparison PDF must both name the one source
    // behind the one county figure they publish.
    ["KNBS 2019 Census", COUNTY_MAP],
    ["KNBS 2019", PDF_COMPARE],
    // A scout visit is a person looking at a plot. Both scout surfaces must
    // keep saying so in their own words, because everything else about the
    // feature — the price, the photographs, the PDF — reads like evidence.
    ["not a survey, title search or ownership verification", SCOUT],
    ["ownership and surveyed boundaries remain unverified", SCOUT_HUB],
    [
      "Device GPS was recorded at upload, not verified media capture location.",
      SCOUT_HUB,
    ],
  ])("contains %s", (needle, source) => {
    expect(source).toContain(needle);
  });
});

describe("forbidden claims on public surfaces", () => {
  const forbidden = [
    "Community-verified",
    "See live intelligence",
    "Real Google Maps signals",
    "Every listing is verified through the HALISIA data pipeline",
    "Verified contributions raise county confidence scores",
    "with verification status and availability",
    "cross-verified",
    "official emblems",
    "persona-weighted 10-module score",
    "halisi-ai.lovable.app",
    "Rated 5 out of 5",
    "const VOICES",
    // Unsourced county metrics, by their display labels.
    "Livability index",
    "Water reliability",
    "YoY growth",
    "Data confidence",
    "Composite of infrastructure",
    "WASREB",
    // Scout claims. "vetted" asserts a screening process that does not exist:
    // scout_profiles holds a self-written display name, counties, availability
    // and bio, and nothing else. "approved" is the true word and the one the
    // rest of the UI already uses.
    //
    // The three "verified X" phrases are deliberately narrow. A bare
    // "verified" would fail on the scout_requests status value
    // payment_verified, which is rendered as text and is accurate; and
    // "verified parcel" would fail on the scout form's own disclaimer, "it is
    // not a verified parcel location", which is a negation and must stay.
    "vetted",
    "verified title",
    "verified owner",
    "verified boundary",
  ];
  it.each(forbidden)("no surface says %s", (needle) => {
    const offenders = PUBLIC_SURFACES.filter(([, src]) => src.includes(needle)).map(([p]) => p);
    expect(offenders).toEqual([]);
  });
});

describe("county figures are sourced, never generated", () => {
  const COUNTY_MODULES = [
    "src/lib/county-metrics.ts",
    "src/lib/county-profile.ts",
    "src/lib/county-politics.ts",
  ];

  it.each(COUNTY_MODULES)("%s derives no figure from a hash of the county code", (path) => {
    const src = read(path);
    // The exact constants the old sine hash and the old opinion jitter used.
    expect(src).not.toContain("12.9898");
    expect(src).not.toContain("43758.5453");
    expect(src).not.toContain("2654435761");
    expect(src).not.toMatch(/Math\.sin\s*\(\s*(seed|code)/);
  });

  it("publishes exactly one county metric, and names its source", () => {
    const metrics = read("src/lib/county-metrics.ts");
    expect(metrics).toContain('export type CountyMetric = "population"');
    expect(metrics).toContain("KNBS 2019");
    // The withdrawn metrics must not reappear in the union type.
    expect(metrics).not.toMatch(/CountyMetric\s*=\s*[^;]*"livability"/);
    expect(metrics).not.toMatch(/CountyMetric\s*=\s*[^;]*"growth"/);
    expect(metrics).not.toMatch(/CountyMetric\s*=\s*[^;]*"water"/);
  });

  it("exposes no composite county score", () => {
    const profile = read("src/lib/county-profile.ts");
    expect(profile).not.toContain("export function dashboardScores");
    expect(profile).not.toContain("export type DashboardScores");
    expect(profile).not.toContain("export function dataConfidencePct");
  });

  it("exposes no county opinion index or invented vote share", () => {
    const politics = read("src/lib/county-politics.ts");
    expect(politics).not.toContain("publicOpinion");
    expect(politics).not.toContain("partyLandscape");
    expect(politics).not.toContain("Afrobarometer");
    expect(politics).not.toContain("tifaresearch");
  });

  it("cites only the sources the county surface actually uses", () => {
    const profile = read("src/lib/county-profile.ts");
    expect(profile).toContain("knbs.or.ke");
    expect(profile).toContain("iebc.or.ke");
    expect(profile).toContain("openstreetmap.org");
    for (const unused of ["wasreb.go.ke", "meteo.go.ke", "ktb.go.ke", "invest.go.ke"]) {
      expect(profile).not.toContain(unused);
    }
  });
});

describe("evidence citations", () => {
  it("uses the correct halisia-ai domain", () => {
    expect(EVIDENCE).toContain("https://halisia-ai.lovable.app/marketplace");
    expect(EVIDENCE).toContain("https://halisia-ai.lovable.app/dashboard");
    expect(EVIDENCE).not.toContain("halisi-ai.lovable.app");
  });

  it("keeps zoning explicitly non-verifiable", () => {
    expect(EVIDENCE).toContain("Not machine-verifiable");
  });
});

describe("landing scenarios are illustrative, not testimonial", () => {
  it("declares illustrative scenarios instead of named quotes", () => {
    expect(LANDING).toContain("const SCENARIOS");
    expect(LANDING).toContain("Before wiring a deposit");
    expect(LANDING).toContain("Buying from abroad");
    expect(LANDING).toContain("Choosing where to spend a site visit");
  });

  it("renders no star rating markup", () => {
    expect(LANDING).not.toMatch(/<Star\b/);
    expect(LANDING).not.toMatch(/<Quote\b/);
  });
});

describe("verification tiers stay distinct", () => {
  it("does not collapse distinct verification states into one label", () => {
    const tiers = [
      "SOURCE_LISTED",
      "DATA_COMPLETENESS",
      "DOCUMENTS_REVIEWED",
      "EVIDENCE_VERIFIED",
      "REGULATOR_VERIFIED",
    ];
    const core = read("src/lib/marketplace.ts");
    const present = tiers.filter((t) => core.includes(t));
    // Whichever tiers this module knows about must remain individually named.
    for (const tier of present) {
      expect(core).toContain(tier);
    }
    expect(new Set(present).size).toBe(present.length);
  });
});

describe("scout provenance is not laundered", () => {
  /**
   * location_source is printed into the scout's brief and stored on the
   * request. It has to describe how the coordinates being sent were obtained,
   * so both provenance branches must re-check that the buyer did not edit the
   * numbers after arriving. The manual_pin branch originally did not.
   */
  it("re-checks the coordinates before claiming either provenance", () => {
    expect(SCOUT).toContain("const untouched =");
    expect(SCOUT).toMatch(/untouched && s\.src === "manual_pin"/);
    expect(SCOUT).toMatch(/untouched && s\.src === "approximate_geocode"/);
  });

  it("treats an empty coordinate parameter as missing, not as zero", () => {
    // `!isNaN(Number(""))` is true, so the old validator turned ?lat=&lng=
    // into the point 0,0 and prefilled the form with it.
    expect(SCOUT).not.toContain("!isNaN(Number(s.lat))");
    expect(SCOUT).not.toContain("!isNaN(Number(s.lng))");
    expect(SCOUT).toContain("Number.isFinite(n) ? n : undefined");
  });
});
